enc = tiktoken.get_encoding("o200k_base")  # Used by newer OpenAI models; try "cl100k_base" for GPT-4/3.5

print(f"{'Text Name':<16} | {'Words':>5} | {'Tokens':>6} | {'Words/Tok':>9} | {'<=8k':>4} | {'<=128k':>6}")
